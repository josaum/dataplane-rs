// Rust guideline compliant 2026-02-21
//! Compiles the vendored Jelly protobuf schemas with tonic service stubs.
//!
//! Two codegen passes run. The first compiles the vendored schemas
//! (`rdf.proto`, `grpc.proto`, `patch.proto`) into their upstream package
//! modules. The second compiles the Atlas-authored `atlas_patch_grpc.proto`
//! service surface into a separate output directory, with `extern_path`
//! mappings so the vendored message types are referenced (never
//! regenerated) — a shared output directory would let the second pass
//! overwrite the first pass's modules with extern-emptied files.

use std::path::{Path, PathBuf};

/// Homebrew install location of `protoc` on macOS developer machines.
///
/// Used only when the `PROTOC` environment variable is not set and the
/// binary exists at this path; otherwise `prost-build` falls back to its
/// default discovery (the `PROTOC` variable, then `protoc` on `PATH`).
const HOMEBREW_PROTOC: &str = "/opt/homebrew/bin/protoc";

/// Creates a prost config with the local protoc fallback applied.
fn config() -> tonic_prost_build::Config {
    let mut config = tonic_prost_build::Config::new();
    if std::env::var_os("PROTOC").is_none() && Path::new(HOMEBREW_PROTOC).exists() {
        config.protoc_executable(HOMEBREW_PROTOC);
    }
    config
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Pass 1: the vendored Jelly schemas (see proto/PROVENANCE.md).
    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .compile_with_config(
            config(),
            &["proto/rdf.proto", "proto/grpc.proto", "proto/patch.proto"],
            &["proto"],
        )?;

    // Pass 2: the Atlas-authored patch pub/sub service. The vendored
    // packages are extern-mapped onto the modules generated by pass 1.
    let atlas_out_dir = PathBuf::from(std::env::var("OUT_DIR")?).join("atlas");
    std::fs::create_dir_all(&atlas_out_dir)?;
    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .out_dir(&atlas_out_dir)
        .extern_path(
            ".eu.ostrzyciel.jelly.core.proto.v1.patch",
            "crate::proto::patch",
        )
        .extern_path(".eu.ostrzyciel.jelly.core.proto.v1", "crate::proto")
        .compile_with_config(config(), &["proto/atlas_patch_grpc.proto"], &["proto"])?;
    Ok(())
}
